#!/usr/bin/env python3
"""Regenerate every Fluctio brand asset from tool/brand/mark.svg.

The mark is mirrored horizontally, then rotated 16 deg counter-clockwise
(the launcher-icon pose). Outputs:

  android/.../drawable/ic_launcher_foreground.xml   adaptive icon
  android/.../mipmap-*/ic_launcher.png              legacy icons (96% fill)
  web/public/icon.svg, icon-maskable.svg            PWA icons
  web/src/app/icon.svg, apple-icon.png              favicon + iOS
  web/public/icon-{192,512}.png, icon-maskable-*.png
  web/src/components/logo-mark-data.ts              web in-app mark layers
  lib/brand/logo_mark_data.dart                     Flutter in-app mark layers

The boot loader is vector-animated in Flutter (lib/brand/logo_mark.dart), so
there is no bitmap to generate. Requires Pillow and a local Chrome/Edge for
SVG rasterization.
"""

from __future__ import annotations

import os
import subprocess
import tempfile
from pathlib import Path
from xml.etree import ElementTree as ET

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
WEB = Path(os.environ.get("FLUCTIO_WEB", ROOT.parent / "fluctio" / "web"))
SRC = ROOT / "tool" / "brand" / "mark.svg"
RES = ROOT / "android" / "app" / "src" / "main" / "res"

SVG_NS = "{http://www.w3.org/2000/svg}"
TRANSFORM = "rotate(-16 512.5 512) translate(1025 0) scale(-1 1)"
# Paint order, as authored in mark.svg. Reveal order is dark -> light with
# white last; the last three land almost together.
DELAYS = [0, 300, 800, 900, 650]


def read_layers() -> list[tuple[str, list[str]]]:
    tree = ET.parse(SRC)
    layers: list[tuple[str, list[str]]] = []
    for node in tree.iter(f"{SVG_NS}path"):
        d = node.get("d")
        fill = node.get("fill")
        if not d or not fill:
            raise SystemExit("mark.svg: every path needs d and fill")
        if layers and layers[-1][0] == fill:
            layers[-1][1].append(d)
        else:
            layers.append((fill, [d]))
    if len(layers) != 5:
        raise SystemExit(f"expected 5 paint-order layers, found {len(layers)}")
    return layers


def mark_svg(inner: str) -> str:
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1025 1024">'
        f'<g transform="{TRANSFORM}">{inner}</g></svg>'
    )


def maskable_svg(inner: str) -> str:
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1025 1024">'
        '<rect width="1025" height="1024" fill="#ffffff"/>'
        '<g transform="translate(512.5 512) scale(0.78) translate(-512.5 -512)">'
        f'<g transform="{TRANSFORM}">{inner}</g></g></svg>'
    )


def inline_paths(layers: list[tuple[str, list[str]]]) -> str:
    return "".join(f'<path d="{d}" fill="{fill}"/>' for fill, ds in layers for d in ds)


def write_android_vector(layers: list[tuple[str, list[str]]]) -> None:
    scale = 72 / 1025
    tx = 54 - scale * 512.5
    ty = 54 - scale * 512
    paths = "\n".join(
        f'            <path android:fillColor="{fill}" android:pathData="{d}" />'
        for fill, ds in layers for d in ds
    )
    xml = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/build_brand_assets.py from tool/brand/mark.svg. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:scaleX="{scale:.6f}"
        android:scaleY="{scale:.6f}"
        android:translateX="{tx:.4f}"
        android:translateY="{ty:.4f}">
        <group
            android:pivotX="512.5"
            android:pivotY="512"
            android:rotation="-16"
            android:scaleX="-1">
{paths}
        </group>
    </group>
</vector>
'''
    (RES / "drawable" / "ic_launcher_foreground.xml").write_text(xml, encoding="utf-8")
    print("android vector")


def chrome() -> str:
    candidates = [
        os.environ.get("CHROME"),
        r"C:/Program Files/Google/Chrome/Application/chrome.exe",
        r"C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe",
    ]
    for c in candidates:
        if c and Path(c).exists():
            return c
    raise SystemExit("Chrome or Edge not found (set CHROME=...)")


CHROME = chrome()


def page(markup: str, white: bool) -> str:
    bg = "#ffffff" if white else "transparent"
    return (
        "<!doctype html><html><head><meta charset=\"utf-8\"><style>"
        f"html,body{{margin:0;background:{bg};overflow:hidden}}svg{{display:block}}"
        f"</style></head><body>{markup}</body></html>"
    )


def raster(svg: str, size: int, white: bool) -> Image.Image:
    markup = svg.replace(
        'viewBox="0 0 1025 1024"',
        f'viewBox="0 0 1025 1024" width="{size}" height="{size}"',
    )
    with tempfile.TemporaryDirectory() as tmp:
        html = Path(tmp) / "page.html"
        html.write_text(page(markup, white), encoding="utf-8")
        out = Path(tmp) / "icon.png"
        args = [
            CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars",
            f"--window-size={size},{size}", f"--screenshot={out}",
        ]
        if not white:
            args.append("--default-background-color=00000000")
        args.append(html.as_uri())
        subprocess.run(args, check=True, capture_output=True)
        return Image.open(out).convert("RGBA")


def write_web_svgs(layers: list[tuple[str, list[str]]]) -> None:
    inner = inline_paths(layers)
    icon = mark_svg(inner) + "\n"
    maskable = maskable_svg(inner) + "\n"
    (WEB / "public" / "icon.svg").write_text(icon, encoding="utf-8")
    (WEB / "src" / "app" / "icon.svg").write_text(icon, encoding="utf-8")
    (WEB / "public" / "icon-maskable.svg").write_text(maskable, encoding="utf-8")
    print("web svgs")


def write_raster_icons(layers: list[tuple[str, list[str]]]) -> None:
    inner = inline_paths(layers)
    art = raster(mark_svg(inner), 1024, white=False)
    bbox = art.getbbox()
    art = art.crop(bbox)
    for density, px in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
        canvas = Image.new("RGBA", (px, px), (0, 0, 0, 0))
        target = round(px * 0.96)
        scaled = art.resize((target, target), Image.LANCZOS)
        off = (px - target) // 2
        canvas.alpha_composite(scaled, (off, off))
        canvas.save(RES / f"mipmap-{density}" / "ic_launcher.png")
    print("android legacy pngs")

    any_1024 = raster(mark_svg(inner), 1024, white=False)
    mask_1024 = raster(maskable_svg(inner), 1024, white=True)
    any_1024.resize((192, 192), Image.LANCZOS).save(WEB / "public" / "icon-192.png")
    any_1024.resize((512, 512), Image.LANCZOS).save(WEB / "public" / "icon-512.png")
    mask_1024.resize((192, 192), Image.LANCZOS).save(WEB / "public" / "icon-maskable-192.png")
    mask_1024.resize((512, 512), Image.LANCZOS).save(WEB / "public" / "icon-maskable-512.png")
    mask_1024.resize((180, 180), Image.LANCZOS).save(WEB / "src" / "app" / "apple-icon.png")
    print("web raster icons")


def write_mark_ts(layers: list[tuple[str, list[str]]]) -> None:
    out = [
        "// Generated by tool/build_brand_assets.py — do not edit by hand.",
        "// Source: tool/brand/mark.svg (paint order; delayMs is reveal order).",
        "export type MarkLayer = { fill: string; d: string[]; delayMs: number };",
        "",
        "export const MARK_LAYERS: MarkLayer[] = [",
    ]
    for i, (fill, ds) in enumerate(layers):
        out.append("  {")
        out.append(f'    fill: "{fill}",')
        out.append(f"    delayMs: {DELAYS[i]},")
        out.append("    d: [")
        for d in ds:
            out.append(f'      "{d}",')
        out.append("    ],")
        out.append("  },")
    out.append("];")
    out.append("")
    (WEB / "src" / "components" / "logo-mark-data.ts").write_text("\n".join(out), encoding="utf-8")
    print("web mark data")


def write_mark_dart(layers: list[tuple[str, list[str]]]) -> None:
    out = [
        "// Generated by tool/build_brand_assets.py — do not edit by hand.",
        "// Source: tool/brand/mark.svg (paint order; delayMs is reveal order).",
        "import 'dart:ui';",
        "",
        "class MarkTier {",
        "  const MarkTier(this.fill, this.delayMs, this.paths);",
        "",
        "  final Color fill;",
        "  final int delayMs;",
        "  final List<String> paths;",
        "}",
        "",
        "const markTiers = <MarkTier>[",
    ]
    for i, (fill, ds) in enumerate(layers):
        argb = "0xFF" + fill.lstrip("#").upper()
        out.append(f"  MarkTier(Color({argb}), {DELAYS[i]}, [")
        for d in ds:
            out.append(f"    '{d}',")
        out.append("  ]),")
    out.append("];")
    out.append("")
    (ROOT / "lib" / "brand").mkdir(parents=True, exist_ok=True)
    (ROOT / "lib" / "brand" / "logo_mark_data.dart").write_text("\n".join(out), encoding="utf-8")
    print("flutter mark data")


def main() -> None:
    layers = read_layers()
    write_android_vector(layers)
    write_web_svgs(layers)
    write_raster_icons(layers)
    write_mark_ts(layers)
    write_mark_dart(layers)


if __name__ == "__main__":
    main()
